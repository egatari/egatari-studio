// CLI と編集アプリが共有する本文の道具を、markdown-it 14.3.3 といっしょに 1 本にする。
//   node tools/build-book-tools.mjs           kit/vendor/book-tools.mjs を作り直す
//   node tools/build-book-tools.mjs --check   作り直したバイトと、保存してあるバイトを比べる
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const require = createRequire(import.meta.url);
const OUT = path.join(ROOT, 'kit', 'vendor', 'book-tools.mjs');
if (require('markdown-it/package.json').version !== '14.3.3') throw new Error('book tools require markdown-it 14.3.3');
// 上流の 2 つの拡張が読む旧拡張子だけを直す。新しい deep import が増えたら、黙って許さずに止める。
const markdownItPlugin = {
  name: 'markdown-it-14-utils',
  setup(b) {
    // vfile 5 の browser 表は neutral では適用されない。上流の可搬実装を明示して使う。
    b.onResolve({ filter: /^\.\/min(?:path|proc|url)\.js$/ }, (a) => {
      if (!a.importer.split(path.sep).join('/').includes('/node_modules/vfile/lib/')) return null;
      return { path: path.resolve(a.resolveDir, a.path.replace(/\.js$/, '.browser.js')) };
    });
    b.onResolve({ filter: /^markdown-it\/lib\// }, (a) => {
      if (!/^markdown-it\/lib\/common\/utils\.(?:js|mjs)$/.test(a.path)) throw new Error(`unexpected markdown-it deep import: ${a.path}`);
      return { path: require.resolve('markdown-it/lib/common/utils.mjs') };
    });
  },
};
const entry = `
export { mystParse, createTokenizer } from 'myst-parser';
export { proofDirective } from 'myst-ext-proof';
export { exerciseDirectives } from 'myst-ext-exercise';
export { liftMystDirectivesAndRolesTransform, mystTargetsTransform, reconstructHtmlTransform, htmlTransform, containerChildrenTransform, captionParagraphTransform } from 'myst-transforms';
export { VFile } from 'vfile';
`;
const NOTICE = `/* Egatari book tools (MIT). Generated by tools/build-book-tools.mjs; do not edit. Bundles myst-parser, myst-transforms, myst-ext-proof, myst-ext-exercise, vfile and their dependencies (markdown-it 14.3.3, punycode.js, unified, js-yaml, he and others; MIT, ISC or BSD licenses). See NOTICE. citeproc-js is not in this file. */\n`;
const result = await esbuild.build({
  absWorkingDir: ROOT,
  stdin: { contents: entry, resolveDir: ROOT, sourcefile: 'tools/book-tools-entry.mjs', loader: 'js' },
  bundle: true, write: false, format: 'esm', platform: 'neutral', target: 'es2022',
  // Browser の条件で Node 専用の crypto/path/process を含めず、両方で使える実装を選ぶ。
  mainFields: ['browser', 'module', 'main'], conditions: ['browser', 'import', 'default'],
  // 文字列の改行と末尾の空白もエスケープし、生成物をどの checkout でも同じバイトにする。
  supported: { 'template-literal': false },
  minify: true, legalComments: 'none', charset: 'utf8', logLevel: 'warning', plugins: [markdownItPlugin],
});
const bytes = Buffer.from(NOTICE + result.outputFiles[0].text);
if (process.argv.includes('--check')) {
  const same = fs.existsSync(OUT) && fs.readFileSync(OUT).equals(bytes);
  console.log(same ? 'kit/vendor/book-tools.mjs matches the installed book tools' : 'kit/vendor/book-tools.mjs is out of date: run npm run book-tools');
  process.exit(same ? 0 : 1);
}
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, bytes);
console.log(`kit/vendor/book-tools.mjs: ${bytes.length} bytes (markdown-it 14.3.3)`);
