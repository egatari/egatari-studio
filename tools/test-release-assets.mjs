// test-all: unit
// リリースに添える名前・ZIP の中身・見本の sha256・本のあるサンプルの印と写しの元（ブラウザとネットワークは使わない）。
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { generate, makeSkillZip } from './make-llm-guide.mjs';
import { EXAMPLES } from './examples-portable.mjs';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const out = fs.mkdtempSync(path.join(os.tmpdir(), 'egatari-release-assets-'));
try {
  const r = spawnSync(process.execPath, [path.join(ROOT, 'tools/release-assets.mjs'), '--out', out], { encoding: 'utf8' });
  assert.equal(r.status, 0, r.stdout + r.stderr);
  const manifest = JSON.parse(fs.readFileSync(path.join(out, 'examples.json'), 'utf8'));
  assert.equal(manifest.version, JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8')).version);
  const names = ['ja', 'en'].map((lang) => `egatari-make-${manifest.version}-${lang}.zip`);
  assert.deepEqual(fs.readdirSync(out).sort(), ['examples.json', ...manifest.examples.map((x) => x.file), ...names].sort());
  for (const [i, lang] of ['ja', 'en'].entries()) {
    assert.ok(r.stdout.includes(names[i]), `lists ${names[i]}`);
    assert.deepEqual(fs.readFileSync(path.join(out, names[i])), makeSkillZip(generate({ skillLang: lang }).files));
  }
  for (const x of manifest.examples) {
    const bytes = fs.readFileSync(path.join(out, x.file));
    assert.equal(bytes.length, x.bytes, x.file);
    assert.equal(createHash('sha256').update(bytes).digest('hex'), x.sha256, x.file);
  }
  console.log('ok release assets list both versioned skill ZIPs with exact generated bytes; example sizes and sha256 match');
  // 本のあるサンプル：一覧の book は本（article）を持つものだけ。写し（egatari/examples の books/<名前>）は SOURCE.json の各ファイルの sha256 どおり
  assert.deepEqual(manifest.examples.map((x) => x.name), EXAMPLES);
  assert.deepEqual(manifest.examples.filter((x) => x.book === true).map((x) => x.name), ['heikin-chuouchi', 'rashomon']);
  assert.ok(manifest.examples.every((x) => typeof x.book === 'boolean'));
  for (const name of ['heikin-chuouchi', 'rashomon']) {
    const dir = path.join(ROOT, 'examples', name);
    const src = JSON.parse(fs.readFileSync(path.join(dir, 'SOURCE.json'), 'utf8'));
    assert.equal(src.repository, 'https://github.com/egatari/examples');
    assert.match(src.commit, /^[0-9a-f]{40}$/);
    const walk = (r) => fs.readdirSync(path.join(dir, r), { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(r, e.name)) : [path.join(r, e.name).split(path.sep).join('/')]));
    const own = new Set(['SOURCE.json', 'sample.json']);   // この写しのために足したもの
    const onDisk = walk('').filter((f) => !own.has(f) && !/(^|\/)(out|\.cache|__pycache__)\//.test(f) && !f.endsWith('.ega.html') && !f.endsWith('.DS_Store')).sort();
    assert.deepEqual(onDisk, Object.keys(src.files).sort(), `${name}: files are the ones in SOURCE.json`);
    for (const f of onDisk) assert.equal(createHash('sha256').update(fs.readFileSync(path.join(dir, f))).digest('hex'), src.files[f], `${name}/${f}: sha256 as in SOURCE.json`);
  }
  console.log('ok the samples with a book (heikin-chuouchi, rashomon) are marked book in examples.json and are unmodified copies of egatari/examples (SOURCE.json)');
} finally { fs.rmSync(out, { recursive: true, force: true }); }
