// test-all: unit
// リリースに添える名前・ZIP の中身・見本の sha256・本のあるサンプルの印と写しの元（ブラウザとネットワークは使わない）。
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { generate, makeSkillZip } from './make-llm-guide.mjs';
import { EXAMPLES } from './examples-portable.mjs';
import { check as checkCopies } from './examples-sync.mjs';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const out = fs.mkdtempSync(path.join(os.tmpdir(), 'egatari-release-assets-'));
try {
  const r = spawnSync(process.execPath, [path.join(ROOT, 'tools/release-assets.mjs'), '--out', out], { encoding: 'utf8' });
  assert.equal(r.status, 0, r.stdout + r.stderr);
  const manifest = JSON.parse(fs.readFileSync(path.join(out, 'examples.json'), 'utf8'));
  assert.equal(manifest.version, JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8')).version);
  const names = ['ja', 'en'].map((lang) => `egatari-make-${manifest.version}-${lang}.zip`);
  assert.deepEqual(fs.readdirSync(out).sort(), ['examples.json', ...manifest.examples.map((x) => x.file), ...names].sort());
  for (const [i, lang] of ['ja', 'en'].entries()) {
    assert.ok(r.stdout.includes(names[i]), `lists ${names[i]}`);
    assert.deepEqual(fs.readFileSync(path.join(out, names[i])), makeSkillZip(generate({ skillLang: lang }).files));
  }
  for (const x of manifest.examples) {
    const bytes = fs.readFileSync(path.join(out, x.file));
    assert.equal(bytes.length, x.bytes, x.file);
    assert.equal(createHash('sha256').update(bytes).digest('hex'), x.sha256, x.file);
  }
  console.log('ok release assets list both versioned skill ZIPs with exact generated bytes; example sizes and sha256 match');
  // 本のあるサンプル：一覧の book は本（article/ か article.md）を持つものだけ。egatari/examples の写し（examples/index.json の path）は SOURCE.json のとおり（tools/examples-sync.mjs）
  assert.deepEqual(manifest.examples.map((x) => x.name), EXAMPLES);
  const BOOKS = EXAMPLES.filter((n) => fs.existsSync(path.join(ROOT, 'examples', n, 'article')) || fs.existsSync(path.join(ROOT, 'examples', n, 'article.md')));
  assert.deepEqual(manifest.examples.filter((x) => x.book === true).map((x) => x.name), BOOKS);
  assert.ok(manifest.examples.every((x) => typeof x.book === 'boolean') && manifest.examples.every((x) => x.cover === null), 'every sample has book, and the release list carries no thumbnails');
  const errs = checkCopies();
  assert.deepEqual(errs, [], 'the copied samples are unmodified copies of egatari/examples (SOURCE.json)');
  console.log(`ok the samples with a book (${BOOKS.join(', ')}) are marked book in examples.json, and the copies of egatari/examples match their SOURCE.json`);
} finally { fs.rmSync(out, { recursive: true, force: true }); }
