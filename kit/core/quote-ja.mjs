// 見出し・題を日本語の「」で引用するときの決まり（一か所）：引用する字の中にすでに「」があれば、中の「」を『』にしてから囲む
//   「春暁」を読む → 「『春暁』を読む」（「「春暁」を読む」にしない）
// 画面の文言・check の知らせ・build の警告で、見出しや題を「」で囲むところはすべてこれを通す。
export const innerJa = (s) => String(s ?? '').replace(/「/g, '『').replace(/」/g, '』');
export const quoteJa = (s) => '「' + innerJa(s) + '」';
