export const WORDS = { ja: JA, en: EN };
const LANG_KEY = 'egatari-play-lang';
export function initialLang() {
  try { const s = localStorage.getItem(LANG_KEY); if (s === 'ja' || s === 'en') return s; } catch { /* storage blocked */ }
  const l = (navigator.languages && navigator.languages[0]) || navigator.language || 'ja';
  return /^ja\b/i.test(l) || !/^[a-z]/i.test(l) ? 'ja' : 'en';
}
export function saveLang(lang) { try { localStorage.setItem(LANG_KEY, lang); } catch { /* storage blocked */ } }
export function apply(lang, root = document) {
  const W = WORDS[lang];
  document.documentElement.lang = lang;
  for (const el of root.querySelectorAll('[data-i18n]')) { const v = W[el.dataset.i18n]; if (typeof v === 'string') el.textContent = v; }
  for (const el of root.querySelectorAll('[data-i18n-label]')) { const v = W[el.dataset.i18nLabel]; if (typeof v === 'string') el.setAttribute('aria-label', v); }
}
